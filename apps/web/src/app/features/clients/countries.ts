export type CountryCode = 'FR' | 'IT' | 'DE' | 'OTHER';

export interface CountryField {
    /** Label printed on the invoice (stored in the client's extra fields) */
    label: string;
    placeholder: string;
    hint?: string;
    /** Expected format, once spaces are removed */
    pattern?: RegExp;
    error?: string;
    /** Expected for this country: warns (without blocking) when empty */
    expected?: boolean;
    uppercase?: boolean;
}

